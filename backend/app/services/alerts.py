"""Proactive administrator alerts, calculated only from stored records.

Every alert is a fact computed with a SELECT (a count, plus the oldest few records so they can be opened). Nothing here is generated by a language
model, and nothing is estimated. What the database cannot answer is listed in `not_tracked` instead of being guessed."""
from __future__ import annotations

from datetime import datetime

from sqlalchemy.orm import Session

from .. import models
from .donor_ml import OPEN_STATUSES
from .live_facts import TERMINAL_DONATION_STATUSES

STALE_DAYS = 14
LIST_LIMIT = 5
_AWAITING_VERIFY = ("pending", "under_review", "info_requested")
_URGENT = ("critical", "high")

NOT_TRACKED = [
    {"key": "overdue_deliveries", "title": "Deliveries past their expected date",
     "reason": "Donations do not store an expected delivery date, so lateness cannot be calculated. The alert below uses the donation date instead."},
    {"key": "failed_workflows", "title": "Failed or delayed donation workflows",
     "reason": "The platform does not keep a log of failed workflow runs, so none can be reported."},
]


def _days(ts, now) -> int | None:
    return max(0, (now - ts).days) if ts else None


def build_alerts(db: Session, now: datetime | None = None) -> dict:
    now = now or datetime.utcnow()
    alerts: list[dict] = []

    needs = [n for n in db.query(models.Need).all() if (n.status or "").lower() in OPEN_STATUSES]
    stale = sorted([n for n in needs if (_days(n.created_at, now) or 0) >= STALE_DAYS], key=lambda n: n.created_at or now)
    if stale:
        urgent = sum(1 for n in stale if (n.urgency or "").lower() in _URGENT)
        alerts.append({
            "key": "stale_needs", "severity": "high" if urgent else "medium", "count": len(stale), "title": f"{len(stale)} need{'s' if len(stale) != 1 else ''} open for {STALE_DAYS}+ days",
            "detail": f"{urgent} of them are critical or high urgency." if urgent else "None are marked critical or high urgency.", "link": "/needs",
            "items": [{"label": f"{n.title or n.category} (#{n.id}), open {_days(n.created_at, now)} days", "link": f"/needs?open={n.id}"} for n in stale[:LIST_LIMIT]]})

    waiting = sorted([o for o in db.query(models.Organization).all() if (o.verification_status or "").lower() in _AWAITING_VERIFY], key=lambda o: o.verification_submitted_at or o.created_at or now)
    if waiting:
        alerts.append({
            "key": "verification", "severity": "medium", "count": len(waiting), "title": f"{len(waiting)} organization{'s' if len(waiting) != 1 else ''} awaiting verification",
            "detail": f"The longest has waited {_days(waiting[0].verification_submitted_at or waiting[0].created_at, now)} days.", "link": "/admin/verification",
            "items": [{"label": f"{o.name}: {(o.verification_status or '').replace('_', ' ')}", "link": "/admin/verification"} for o in waiting[:LIST_LIMIT]]})

    flags = db.query(models.DonationFlag).filter(models.DonationFlag.review_decision.is_(None)).order_by(models.DonationFlag.flagged_at.asc()).all()
    if flags:
        alerts.append({
            "key": "anomalies", "severity": "high", "count": len(flags), "title": f"{len(flags)} unusual donation{'s' if len(flags) != 1 else ''} waiting for review",
            "detail": "These are review signals, not proof of fraud.", "link": "/ai/fraud",
            "items": [{"label": f"Donation #{f.donation_id}, flagged {_days(f.flagged_at, now)} days ago", "link": "/ai/fraud"} for f in flags[:LIST_LIMIT]]})

    pending = sorted([d for d in db.query(models.Donation).all() if (d.status or "unspecified").lower() not in TERMINAL_DONATION_STATUSES and (_days(d.timestamp, now) or 0) >= STALE_DAYS],
                     key=lambda d: d.timestamp or now)
    if pending:
        alerts.append({
            "key": "undelivered", "severity": "medium", "count": len(pending), "title": f"{len(pending)} donation{'s' if len(pending) != 1 else ''} not delivered after {STALE_DAYS}+ days",
            "detail": "Counted from the donation date, because no expected delivery date is stored.", "link": "/donations",
            "items": [{"label": f"Donation #{d.id}, status {d.status or 'unspecified'}, {_days(d.timestamp, now)} days old", "link": f"/donations?open={d.id}"} for d in pending[:LIST_LIMIT]]})

    order = {"high": 0, "medium": 1, "low": 2}
    alerts.sort(key=lambda a: (order[a["severity"]], -a["count"]))
    return {"generated_at": now.isoformat(timespec="seconds"), "alerts": alerts, "not_tracked": NOT_TRACKED, "stale_days": STALE_DAYS}
